-- DDL tham chiếu cho PostgreSQL (dùng khi chuyển sang Flyway/Liquibase, ddl-auto=validate)
CREATE TABLE carts (
    cart_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          VARCHAR(64),
    guest_session_id VARCHAR(64),
    status           VARCHAR(20)    NOT NULL,
    subtotal         NUMERIC(19, 2) NOT NULL DEFAULT 0,
    version          BIGINT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ    NOT NULL,
    updated_at       TIMESTAMPTZ    NOT NULL,
    CONSTRAINT ck_carts_status CHECK (status IN ('EMPTY', 'ACTIVE', 'CANCELLED', 'PAID')),
    CONSTRAINT ck_carts_owner  CHECK (user_id IS NOT NULL OR guest_session_id IS NOT NULL)
);
CREATE INDEX idx_carts_user_id          ON carts (user_id);
CREATE INDEX idx_carts_guest_session_id ON carts (guest_session_id);

CREATE TABLE cart_items (
    item_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT         NOT NULL REFERENCES carts (cart_id) ON DELETE CASCADE,
    product_id BIGINT         NOT NULL,
    sku_id     VARCHAR(100)   NOT NULL,
    quantity   INTEGER        NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(19, 2) NOT NULL CHECK (unit_price >= 0),
    CONSTRAINT uq_cart_items_cart_product_sku UNIQUE (cart_id, product_id, sku_id)
);
CREATE INDEX idx_cart_items_cart_id ON cart_items (cart_id);
